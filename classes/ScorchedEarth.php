/**
 * ScorchedEarth.php
 * ============================================================
 * Embeds decoy records with specific sentinel UUIDs into the
 * database. These records are invisible to legitimate frontend
 * code — they are ONLY returned when an attacker uses SQL
 * injection, a compromised API key, or internal misconfiguration
 * to bypass normal query scoping.
 *
 * When a sentinel UUID appears in any request (GET, POST, DELETE),
 * the tripwire fires:
 *   1. Session immediately banned
 *   2. API key revoked
 *   3. WhatsApp + physical tracker alert
 *   4. Event logged as SCORCHED_EARTH_TRIGGER
 *
 * Decoy records are system-type aware:
 *   ECOMMERCE/PAYMENT  → fake merchant account, TZS 99,999,999 balance
 *   EDUCATION          → fake admin lecturer with perfect grades
 *   WIFI_MANAGEMENT    → fake unlimited-bandwidth master subscriber
 *   HEALTHCARE         → fake senior doctor with full access
 *   AGENCY             → fake platinum client, 10M followers
 * ============================================================
 */

namespace Aegis\Classes;

use Aegis\Config\Database;

class ScorchedEarth
{
    // UUID prefix that is NEVER generated by real business logic
    // If it appears in any request parameter, it is 100% attacker
    public const SENTINEL_PREFIX  = '0000DEAD-';
    public const SENTINEL_PATTERN = '/^0000DEAD-/';

    // Sentinel IDs per system type — embed these in decoy DB rows
